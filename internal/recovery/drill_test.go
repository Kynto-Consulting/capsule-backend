// TestLocalDrill is the local recovery drill (DR-BACKUP.md section 8) with what this machine has:
//   - REAL: the backup envelope (AES-256-GCM chunks, wrapped key), sha256 checks, manifest checks,
//     the plan/engine/journal/report code, and deploy/recovery/git-restore.sh with real openssl,
//     sha256sum and tar on a fabricated forgejo dump.
//   - FAKED: S3 (DirStore on a temp dir, not MinIO), the databases (a dump file, not a Postgres
//     restore), Forgejo itself (no server; only the dump layout), Docker/containers.
func TestLocalDrill(t *testing.T) {
	if testing.Short() {
		t.Skip("local drill takes about 40 s (600k PBKDF2 iterations, run twice)")
	}
	bash, err := exec.LookPath("bash")
	if err != nil {
		t.Skip("bash not available")
	}
	for _, tool := range []string{"openssl", "tar", "sha256sum", "git"} {
		if _, err := exec.LookPath(tool); err != nil {
			t.Skipf("%s not available", tool)
		}
	}
	_ = bash
	ctx := context.Background()
	store := &DirStore{Root: t.TempDir()}
	v := &Verifier{Store: store, Secret: testSecret}
	pid, run, dbID := uuid.New(), uuid.New(), uuid.New()
	started := time.Now().UTC().Add(-2 * time.Hour)

	// 1. backups generated by the test itself, with the production envelope
	dump := bytes.Repeat([]byte("INSERT INTO t VALUES (1);\n"), 50000)
	put(t, store, backup.ObjectKey(pid, "manifest", started, run, "json"), manifestFor(pid, run, dbID), "manifest", "manifest", &pid, started)
	put(t, store, backup.ObjectKey(pid, "database", started, run, dbID.String()[:8]+".pgdump"), dump, "database", "main", &pid, started)
	put(t, store, backup.ObjectKey(pid, "volume", started, run, "tar.gz"), []byte("volume-bytes"), "volume", "capsule-data-"+pid.String(), &pid, started)

	// 2. a forgejo dump exactly as forgejo-backup.sh writes it (encrypted, sidecar .sha256)
	work := t.TempDir()
	pass := "drill-passphrase"
	script := `set -e
mkdir -p dump/repos/org/r1.git dump/data && git init -q --bare dump/repos/org/r1.git
echo "[server]" > dump/app.ini && echo x > dump/data/a.txt
tar -czf d.tar.gz -C dump .
mkdir -p "$ROOT/forgejo"
openssl enc -aes-256-cbc -pbkdf2 -iter 600000 -salt -pass env:GIT_BACKUP_PASSPHRASE -in d.tar.gz -out "$ROOT/forgejo/forgejo-dump-20261102T091700Z.tar.gz.enc"
sha256sum "$ROOT/forgejo/forgejo-dump-20261102T091700Z.tar.gz.enc" > "$ROOT/forgejo/forgejo-dump-20261102T091700Z.tar.gz.enc.sha256"`
	cmd := exec.Command("bash", "-c", script)
	cmd.Dir = work
	cmd.Env = append(os.Environ(), "ROOT="+filepath.ToSlash(store.Root), "GIT_BACKUP_PASSPHRASE="+pass)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("fabricating the dump: %v\n%s", err, out)
	}

	// 3. catalog from the bucket alone (bootstrap mode), then the plan
	cat, err := CatalogFromBucket(ctx, store, v, store, time.Now().UTC())
	if err != nil {
		t.Fatal(err)
	}
	if len(cat.ForgejoDumps) != 1 || cat.ForgejoDumps[0].Sha256 == "" {
		t.Fatalf("dump not found with its sidecar: %+v", cat.ForgejoDumps)
	}
	req := Request{Mode: ModeApply, All: true, Target: TargetEphemeral, Scopes: []Scope{ScopeGit, ScopeDatabases, ScopeVolumes, ScopeProjects}}
	plan, err := BuildPlan(req, cat)
	if err != nil {
		t.Fatal(err)
	}
	if !plan.Ready {
		t.Fatalf("plan not ready: %+v", plan.Blockers())
	}

	// 4. run it
	dest := t.TempDir()
	restoreDir := filepath.Join(dest, "ephemeral")
	gitDir := filepath.Join(dest, "forgejo-data")
	t.Setenv("RECOVERY_SOURCE_DIR", store.Root)
	t.Setenv("GIT_BACKUP_PASSPHRASE", pass)
	t.Setenv("RECOVERY_DATA_DIR", filepath.ToSlash(gitDir))
	t.Setenv("RECOVERY_SKIP_DB_LOAD", "1")
	rest := &DirRestorer{V: v, Dir: restoreDir}
	j := NewMemJournal()
	var reportKey string
	mkEngine := func() *Engine {
		return &Engine{Journal: j, Now: time.Now, Execs: map[Kind]Exec{
			KindPreflight: PreflightExec{V: v, Probe: probeSnapshot(plan)},
			KindDatabase:  DataExec{R: rest}, KindVolume: DataExec{R: rest},
			KindProject: ProjectExec{V: v, Dir: restoreDir},
			KindGit:     ScriptExec{Runner: OSRunner{}, Dir: filepath.Join("..", "..", "..", "deploy", "recovery"), Script: "git-restore.sh"},
			KindReport: ReportExec{Build: func(ctx context.Context, rc RunCtx) (string, error) {
				cur, _ := j.Get(ctx, rc.RunID)
				rep := BuildReport(cur, plan, time.Now().UTC(), time.Time{}, nil)
				k, err := WriteReport(ctx, store, "drills/", rep)
				reportKey = k
				return k, err
			}},
		}}
	}
	exec1 := func() *Run {
		r := &Run{ID: uuid.New(), Mode: ModeApply, Request: plan.Request, StartedAt: time.Now().UTC()}
		if _, _, err := j.Begin(ctx, r); err != nil {
			t.Fatal(err)
		}
		if err := mkEngine().Execute(ctx, plan, r); err != nil {
			t.Fatal(err)
		}
		return r
	}
	first := exec1()
	for _, s := range first.Steps {
		t.Logf("[%s] %s: %s", s.Status, s.Name, s.Detail)
		if s.Status == StepFailed {
			t.Fatalf("step failed: %s: %s", s.Name, s.Detail)
		}
	}
	// smoke has no executor here, so it is `skipped`; everything else must be ok
	if first.Status != RunSuccess {
		t.Fatalf("status %s", first.Status)
	}
	got, _ := os.ReadFile(filepath.Join(restoreDir, pid.String(), "database", dbID.String()[:8]+"-"+dbID.String()[:8]))
	if !bytes.Equal(got, dump) {
		t.Fatalf("restored database dump differs (%d bytes)", len(got))
	}
	if _, err := os.Stat(filepath.Join(gitDir, "git", "repositories", "org", "r1.git")); err != nil {
		t.Fatalf("git repository not restored: %v", err)
	}
	if reportKey == "" {
		t.Fatal("no report written")
	}
	rb, _, _ := store.Download(ctx, reportKey)
	var rep Report
	_ = json.NewDecoder(rb).Decode(&rep)
	rb.Close()
	if rep.WorstRPOHrs < 1 || len(rep.Used) != 4 { // dump + database + volume + manifest? (manifest is not a step snapshot)
		t.Logf("report: rpo=%dh used=%d", rep.WorstRPOHrs, len(rep.Used))
	}
	if !strings.Contains(string(mustJSON(rep)), "plan_id") {
		t.Fatal("report lacks the plan id")
	}

	// 5. second pass over the same destination: every restore step reports "already done"
	second := exec1()
	done := 0
	for _, s := range second.Steps {
		if strings.HasPrefix(s.Detail, "already done") {
			done++
		}
	}
	if done < 3 { // database, volume and git
		t.Fatalf("second run re-applied steps: %+v", second.Steps)
	}

	// 6. tamper with the database dump in the bucket: the run must fail that step and keep the data
	for _, s := range plan.Steps {
		if s.Kind == KindDatabase {
			obj := store.file(s.Snapshot.ObjectKey)
			raw, _ := os.ReadFile(obj)
			raw[len(raw)/2] ^= 0xff
			_ = os.WriteFile(obj, raw, 0o644)
		}
	}
	plan2 := plan
	plan2.Request.ForceOverwrite = true
	r3 := &Run{ID: uuid.New(), Mode: ModeVerify, Request: plan2.Request, StartedAt: time.Now().UTC()}
	_, _, _ = j.Begin(ctx, r3)
	plan2.Request.Mode = ModeVerify
	if err := mkEngine().Execute(ctx, plan2, r3); err != nil {
		t.Fatal(err)
	}
	if r3.Status == RunSuccess {
		t.Fatal("verify must not succeed with a tampered backup")
	}
	after, _ := os.ReadFile(filepath.Join(restoreDir, pid.String(), "database", dbID.String()[:8]+"-"+dbID.String()[:8]))
	if !bytes.Equal(after, dump) {
		t.Fatal("verify changed restored data")
	}
}

func mustJSON(v any) []byte { b, _ := json.Marshal(v); return b }
