// Symbolic walk of the router

type scope struct {
	pkg    *pkgInfo
	prefix string
	auth   bool
	vars   map[types.Object]string
	fn     string // display name of the enclosing function, for func literal labels
}

func (s scope) child() scope {
	v := make(map[types.Object]string, len(s.vars))
	for k, x := range s.vars {
		v[k] = x
	}
	s.vars = v
	return s
}

type walker struct {
	l      *loader
	routes map[string]Row // method + " " + path, last registration wins
	order  []string
	errs   []string
	depth  int
	visits map[string]int // function bodies walked (guards recursion)
}

func (w *walker) errorf(pos token.Pos, format string, a ...any) {
	w.errs = append(w.errs, fmt.Sprintf("%s: %s", w.l.fset.Position(pos), fmt.Sprintf(format, a...)))
}

// Extract returns the golden rows of the router in dir.
func Extract(dir string) ([]Row, error) {
	l, err := loadModule(dir)
	if err != nil {
		return nil, err
	}
	rp := l.pkgs[l.module+"/"+routerPkg]
	if rp == nil {
		return nil, fmt.Errorf("package %s not found", routerPkg)
	}
	var start *funcInfo
	for _, f := range l.funcs {
		if f.pkg == rp && f.decl.Name.Name == routerFunc && f.decl.Recv == nil {
			start = f
		}
	}
	if start == nil {
		return nil, fmt.Errorf("function %s not found", routerFunc)
	}
	w := &walker{l: l, routes: map[string]Row{}, visits: map[string]int{}}
	w.walkBody(start.decl.Body.List, scope{pkg: rp, vars: map[types.Object]string{}, fn: start.name})
	if len(w.errs) > 0 {
		return nil, fmt.Errorf("%d problems:\n  %s", len(w.errs), strings.Join(w.errs, "\n  "))
	}
	rows := make([]Row, 0, len(w.order))
	for _, k := range w.order {
		rows = append(rows, w.routes[k])
	}
	rows, err = applyClasses(rows)
	if err != nil {
		return nil, err
	}
	return rows, nil
}

func (w *walker) isRouter(s scope, e ast.Expr) bool {
	t := s.pkg.info.TypeOf(e)
	if t == nil {
		return false
	}
	if p, ok := t.(*types.Pointer); ok {
		t = p.Elem()
	}
	n, ok := t.(*types.Named)
	if !ok || n.Obj().Pkg() == nil || n.Obj().Pkg().Path() != chiPath {
		return false
	}
	switch n.Obj().Name() {
	case "Router", "Mux", "Routes":
		return true
	}
	return false
}

func (w *walker) evalString(s scope, e ast.Expr) (string, bool) {
	if tv, ok := s.pkg.info.Types[e]; ok && tv.Value != nil && tv.Value.Kind() == constant.String {
		return constant.StringVal(tv.Value), true
	}
	switch x := e.(type) {
	case *ast.ParenExpr:
		return w.evalString(s, x.X)
	case *ast.BinaryExpr:
		if x.Op == token.ADD {
			a, ok1 := w.evalString(s, x.X)
			b, ok2 := w.evalString(s, x.Y)
			return a + b, ok1 && ok2
		}
	case *ast.Ident:
		if o := s.pkg.info.Uses[x]; o != nil {
			if v, ok := s.vars[o]; ok {
				return v, true
			}
		}
		if o := s.pkg.info.Defs[x]; o != nil {
			if v, ok := s.vars[o]; ok {
				return v, true
			}
		}
	}
	return "", false
}

func (w *walker) walkBody(stmts []ast.Stmt, s scope) {
	for _, st := range stmts {
		w.walkStmt(st, &s)
	}
}

func (w *walker) walkStmt(st ast.Stmt, s *scope) {
	switch x := st.(type) {
	case *ast.ExprStmt:
		if call, ok := x.X.(*ast.CallExpr); ok {
			w.walkCall(call, s)
		}
	case *ast.AssignStmt:
		if len(x.Lhs) == len(x.Rhs) {
			for i, lhs := range x.Lhs {
				id, ok := lhs.(*ast.Ident)
				if !ok {
					continue
				}
				if v, ok := w.evalString(*s, x.Rhs[i]); ok {
					obj := s.pkg.info.Defs[id]
					if obj == nil {
						obj = s.pkg.info.Uses[id]
					}
					if obj != nil {
						s.vars[obj] = v
					}
				}
			}
		}
	case *ast.DeclStmt:
		// const/var strings are constants for go/types (handled by evalString) or tracked as vars
		if gd, ok := x.Decl.(*ast.GenDecl); ok {
			for _, sp := range gd.Specs {
				if vs, ok := sp.(*ast.ValueSpec); ok && len(vs.Names) == len(vs.Values) {
					for i, n := range vs.Names {
						if v, ok := w.evalString(*s, vs.Values[i]); ok {
							if obj := s.pkg.info.Defs[n]; obj != nil {
								s.vars[obj] = v
							}
						}
					}
				}
			}
		}
	case *ast.IfStmt:
		if x.Init != nil {
			w.walkStmt(x.Init, s)
		}
		c := s.child()
		w.walkBody(x.Body.List, c)
		if x.Else != nil {
			switch e := x.Else.(type) {
			case *ast.BlockStmt:
				w.walkBody(e.List, s.child())
			default:
				cc := s.child()
				w.walkStmt(e, &cc)
			}
		}
	case *ast.BlockStmt:
		w.walkBody(x.List, s.child())
	case *ast.ForStmt:
		w.walkBody(x.Body.List, s.child())
	case *ast.RangeStmt:
		w.walkBody(x.Body.List, s.child())
	case *ast.SwitchStmt:
		for _, c := range x.Body.List {
			if cc, ok := c.(*ast.CaseClause); ok {
				w.walkBody(cc.Body, s.child())
			}
		}
	}
}

var verbs = map[string]string{
	"Get": "GET", "Post": "POST", "Put": "PUT", "Patch": "PATCH", "Delete": "DELETE",
	"Head": "HEAD", "Options": "OPTIONS", "Connect": "CONNECT", "Trace": "TRACE",
}

func (w *walker) walkCall(call *ast.CallExpr, s *scope) {
	sel, isSel := call.Fun.(*ast.SelectorExpr)
	if isSel && w.isRouter(*s, sel.X) {
		name := sel.Sel.Name
		switch {
		case verbs[name] != "":
			w.register(call, *s, verbs[name], 0, 1)
			return
		case name == "Handle" || name == "HandleFunc":
			w.register(call, *s, "ANY", 0, 1)
			return
		case name == "Method" || name == "MethodFunc":
			m, ok := w.evalString(*s, call.Args[0])
			if !ok {
				w.errorf(call.Pos(), "cannot evaluate the HTTP method")
				return
			}
			w.register(call, *s, strings.ToUpper(m), 1, 2)
			return
		case name == "Use":
			for _, a := range call.Args {
				if strings.Contains(exprString(a), "middleware.Auth(") {
					s.auth = true
				}
			}
			return
		case name == "Group":
			if lit, ok := call.Args[0].(*ast.FuncLit); ok {
				w.walkBody(lit.Body.List, s.child())
			} else {
				w.errorf(call.Pos(), "Group with a non-literal function")
			}
			return
		case name == "Route":
			pat, ok := w.evalString(*s, call.Args[0])
			lit, isLit := call.Args[1].(*ast.FuncLit)
			if !ok || !isLit {
				w.errorf(call.Pos(), "Route with a non-literal pattern or function")
				return
			}
			c := s.child()
			c.prefix += pat
			w.walkBody(lit.Body.List, c)
			return
		case name == "With":
			return
		case name == "NotFound" || name == "MethodNotAllowed":
			return
		case name == "Mount":
			w.errorf(call.Pos(), "Mount is not supported by the extractor: add support or register routes directly")
			return
		}
	}
	// r.With(...).Get(...): the receiver is a call returning a router
	if isSel {
		if inner, ok := sel.X.(*ast.CallExpr); ok {
			if isel, ok := inner.Fun.(*ast.SelectorExpr); ok && isel.Sel.Name == "With" && w.isRouter(*s, isel.X) && verbs[sel.Sel.Name] != "" {
				w.register(call, *s, verbs[sel.Sel.Name], 0, 1)
				return
			}
		}
	}
	// a module function or method that receives the router: descend into it
	hasRouter := false
	for _, a := range call.Args {
		if w.isRouter(*s, a) {
			hasRouter = true
		}
	}
	if !hasRouter {
		return
	}
	fi := w.calleeFunc(*s, call)
	if fi == nil {
		w.errorf(call.Pos(), "a router is passed to a function whose body is not available (%s)", exprString(call.Fun))
		return
	}
	if w.depth > 8 {
		w.errorf(call.Pos(), "router nesting too deep at %s", fi.name)
		return
	}
	c := scope{pkg: fi.pkg, prefix: s.prefix, auth: s.auth, vars: map[types.Object]string{}, fn: fi.name}
	// bind string parameters
	if fi.decl.Type.Params != nil {
		i := 0
		for _, f := range fi.decl.Type.Params.List {
			for _, n := range f.Names {
				if i < len(call.Args) {
					if v, ok := w.evalString(*s, call.Args[i]); ok {
						if o := fi.pkg.info.Defs[n]; o != nil {
							c.vars[o] = v
						}
					}
				}
				i++
			}
			if len(f.Names) == 0 {
				i++
			}
		}
	}
	w.depth++
	w.walkBody(fi.decl.Body.List, c)
	w.depth--
}

// calleeFunc resolves the module function or method called by call.
func (w *walker) calleeFunc(s scope, call *ast.CallExpr) *funcInfo {
	var obj types.Object
	switch f := call.Fun.(type) {
	case *ast.Ident:
		obj = s.pkg.info.Uses[f]
	case *ast.SelectorExpr:
		if sl := s.pkg.info.Selections[f]; sl != nil {
			obj = sl.Obj()
		} else {
			obj = s.pkg.info.Uses[f.Sel]
		}
	}
	if fn, ok := obj.(*types.Func); ok {
		return w.l.funcs[fn.FullName()]
	}
	return nil
}

func exprString(e ast.Expr) string {
	var b bytes.Buffer
	var write func(ast.Node)
	write = func(n ast.Node) {
		switch x := n.(type) {
		case *ast.Ident:
			b.WriteString(x.Name)
		case *ast.SelectorExpr:
			write(x.X)
			b.WriteString(".")
			b.WriteString(x.Sel.Name)
		case *ast.CallExpr:
			write(x.Fun)
			b.WriteString("(")
		case *ast.StarExpr:
			b.WriteString("*")
			write(x.X)
		}
	}
	write(e)
	return b.String()
}

// register records a route registration whose path is Args[pi] and whose handler is Args[hi].
func (w *walker) register(call *ast.CallExpr, s scope, method string, pi, hi int) {
	if len(call.Args) <= hi {
		w.errorf(call.Pos(), "route registration with too few arguments")
		return
	}
	pat, ok := w.evalString(s, call.Args[pi])
	if !ok {
		w.errorf(call.Pos(), "cannot evaluate the path %s", exprString(call.Args[pi]))
		return
	}
	path := s.prefix + pat
	roots, label := w.handlerRoots(s, call.Args[hi])
	if len(roots) == 0 {
		w.errorf(call.Pos(), "cannot resolve the handler of %s %s", method, path)
	}
	acts := map[string]bool{}
	seen := map[string]bool{}
	for _, r := range roots {
		w.collectActions(r.pkg, r.node, acts, seen, 0)
	}
	row := Row{Method: method, Path: path, Handler: label, Auth: "public", Class: "action"}
	if s.auth {
		row.Auth = "session"
	}
	for a := range acts {
		row.Actions = append(row.Actions, a)
	}
	sort.Strings(row.Actions)
	if len(row.Actions) == 0 {
		row.Class = "" // filled by classes.go or reported
	}
	key := method + " " + path
	if _, dup := w.routes[key]; !dup {
		w.order = append(w.order, key)
	}
	w.routes[key] = row // chi lets the last registration win
}

type root struct {
	pkg  *pkgInfo
	node ast.Node
}

// handlerRoots resolves a handler expression to the function bodies that implement it.
func (w *walker) handlerRoots(s scope, e ast.Expr) ([]root, string) {
	switch x := e.(type) {
	case *ast.FuncLit:
		w.l.litCount[s.fn]++
		return []root{{s.pkg, x}}, fmt.Sprintf("%s.func%d", s.fn, w.l.litCount[s.fn])
	case *ast.ParenExpr:
		return w.handlerRoots(s, x.X)
	case *ast.CallExpr:
		// conversion such as http.HandlerFunc(h), or a constructor that returns a handler
		if tv, ok := s.pkg.info.Types[x.Fun]; ok && tv.IsType() && len(x.Args) == 1 {
			return w.handlerRoots(s, x.Args[0])
		}
		var roots []root
		label := ""
		if fi := w.calleeFunc(s, x); fi != nil {
			roots = append(roots, root{fi.pkg, fi.decl})
			label = fi.name
		}
		for _, a := range x.Args {
			r, l := w.handlerRoots(s, a)
			roots = append(roots, r...)
			if label == "" {
				label = l
			}
		}
		return roots, label
	case *ast.UnaryExpr, *ast.CompositeLit:
		// &Handler{...}: an http.Handler value; its ServeHTTP is the handler
		if t := s.pkg.info.TypeOf(e); t != nil {
			if o, _, _ := types.LookupFieldOrMethod(t, true, s.pkg.pkg, "ServeHTTP"); o != nil {
				if fn, ok := o.(*types.Func); ok {
					if fi := w.l.funcs[fn.FullName()]; fi != nil {
						return []root{{fi.pkg, fi.decl}}, fi.name
					}
				}
			}
		}
	case *ast.SelectorExpr, *ast.Ident:
		var obj types.Object
		if se, ok := x.(*ast.SelectorExpr); ok {
			if sl := s.pkg.info.Selections[se]; sl != nil {
				obj = sl.Obj()
			} else {
				obj = s.pkg.info.Uses[se.Sel]
			}
		} else {
			obj = s.pkg.info.Uses[x.(*ast.Ident)]
		}
		if fn, ok := obj.(*types.Func); ok {
			if fi := w.l.funcs[fn.FullName()]; fi != nil {
				return []root{{fi.pkg, fi.decl}}, fi.name
			}
		}
	}
	return nil, ""
}

// collectActions gathers authz.Action constants referenced in node and, transitively, in the module
// functions it calls (never descending into the authz package itself).
func (w *walker) collectActions(p *pkgInfo, node ast.Node, acts map[string]bool, seen map[string]bool, depth int) {
	ast.Inspect(node, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.GoStmt:
			return false // work launched in the background is not part of the request decision
		case *ast.SelectorExpr:
			if c, ok := p.info.Uses[x.Sel].(*types.Const); ok && c.Pkg() != nil && strings.HasSuffix(c.Pkg().Path(), authzSuffix) {
				if nt, ok := c.Type().(*types.Named); ok && nt.Obj().Name() == "Action" {
					acts[constant.StringVal(c.Val())] = true
				}
			}
		case *ast.CallExpr:
			if depth >= maxCallDepth {
				return true
			}
			if fi := w.calleeFunc(scope{pkg: p}, x); fi != nil && !strings.HasSuffix(fi.pkg.path, authzSuffix) {
				key := fi.pkg.path + "." + fi.name
				if !seen[key] {
					seen[key] = true
					w.collectActions(fi.pkg, fi.decl.Body, acts, seen, depth+1)
				}
			}
		}
		return true
	})
}
