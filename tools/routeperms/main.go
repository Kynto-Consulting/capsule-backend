// Command routeperms extracts, with go/ast and go/types, the table "route -> authorization it needs
// today" from the real router (internal/server.newRouter and every Mount* function it calls) and writes it
// as internal/authz/routes_authz.golden.
//
// Why: the permission engine (docs/permissions, MIGRATION F0) replaces the old authz actions by atomic
// permissions route by route. This golden file is the checked-in baseline of what every route requires
// BEFORE the change: the handler migration packages (P3b) must keep the decision of every route, and a new
// route without a row fails the build (test in this package; `make routes-check`).
//
// Method: it type-checks the module's packages from source (dependencies come from `go list -export`
// data), walks newRouter symbolically (Route/Group/prefix variables/Mount* calls with a chi.Router
// argument, conditional mounts included), resolves each handler to its function body, and collects the
// authz.Action constants referenced by that body and by the module functions it calls (the authz package
// itself excluded). Routes whose authorization is not an authz.Action are classified in classes.go, and the
// extractor FAILS if a route has neither an action nor a classification, or if a classification is stale.
//
// Usage (from the backend directory):
//
//	go run ./tools/routeperms            write internal/authz/routes_authz.golden
//	go run ./tools/routeperms -check     fail when the file is stale
//	go run ./tools/routeperms -list      print the rows to stdout
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/constant"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const (
	routerPkg    = "internal/server"
	routerFunc   = "newRouter"
	chiPath      = "github.com/go-chi/chi/v5"
	goldenRel    = "internal/authz/routes_authz.golden"
	authzSuffix  = "/internal/authz"
	maxCallDepth = 3
)

func main() {
	check := flag.Bool("check", false, "fail if the golden file is stale instead of writing it")
	list := flag.Bool("list", false, "print the golden rows to stdout")
	dir := flag.String("dir", ".", "backend module directory")
	flag.Parse()

	rows, err := Extract(*dir)
	if err != nil {
		fmt.Fprintln(os.Stderr, "routeperms:", err)
		os.Exit(1)
	}
	out := Render(rows)
	switch {
	case *list:
		os.Stdout.Write(out)
	case *check:
		cur, err := os.ReadFile(filepath.Join(*dir, goldenRel))
		if err != nil || !bytes.Equal(cur, out) {
			fmt.Fprintln(os.Stderr, "routeperms: routes_authz.golden is stale; run `make routes-gen` (go run ./tools/routeperms)")
			os.Exit(1)
		}
	default:
		if err := os.WriteFile(filepath.Join(*dir, goldenRel), out, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "routeperms:", err)
			os.Exit(1)
		}
		fmt.Printf("routeperms: %d routes written to %s\n", len(rows), goldenRel)
	}
}

// Row is one route of the golden file.
type Row struct {
	Method  string
	Path    string
	Handler string
	Auth    string   // public | session
	Class   string   // action | org-member | ... (see classes.go)
	Actions []string // old authz actions found in the handler
}

// Render formats the golden file: sorted, tab-separated, with a header describing the columns.
func Render(rows []Row) []byte {
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].Path != rows[j].Path {
			return rows[i].Path < rows[j].Path
		}
		return rows[i].Method < rows[j].Method
	})
	var b bytes.Buffer
	b.WriteString("# routes_authz.golden: every route of the Capsule router and the authorization it needs TODAY.\n")
	b.WriteString("# Generated by `go run ./tools/routeperms` (backend/tools/routeperms); do not edit by hand.\n")
	b.WriteString("# Columns (tab separated): METHOD, PATH, HANDLER, AUTH, CLASS, OLD_ACTIONS\n")
	b.WriteString("#   AUTH     public = no authentication middleware; session = middleware.Auth (session or cap_ token)\n")
	b.WriteString("#   CLASS    action = decided by authz.Service with OLD_ACTIONS; other classes are listed in tools/routeperms/classes.go\n")
	b.WriteString("#   OLD_ACTIONS  comma separated authz actions the handler checks ('-' when the class is not action)\n")
	for _, r := range rows {
		acts := strings.Join(r.Actions, ",")
		if acts == "" {
			acts = "-"
		}
		fmt.Fprintf(&b, "%s\t%s\t%s\t%s\t%s\t%s\n", r.Method, r.Path, r.Handler, r.Auth, r.Class, acts)
	}
	return b.Bytes()
}

