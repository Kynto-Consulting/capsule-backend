// Loading

type listedPkg struct {
	ImportPath string
	Dir        string
	Export     string
	GoFiles    []string
	CgoFiles   []string
	Standard   bool
	Module     *struct{ Path string }
}

type pkgInfo struct {
	path  string
	files []*ast.File
	pkg   *types.Package
	info  *types.Info
}

type funcInfo struct {
	decl *ast.FuncDecl
	pkg  *pkgInfo
	name string // display name, e.g. handlers.ProjectHandler.Get
}

type loader struct {
	fset     *token.FileSet
	module   string
	pkgs     map[string]*pkgInfo // module packages by import path
	funcs    map[string]*funcInfo
	exports  map[string]string
	imp      types.Importer
	litCount map[string]int
}

func loadModule(dir string) (*loader, error) {
	cmd := exec.Command("go", "list", "-export", "-deps", "-json", "./internal/server/...")
	cmd.Dir = dir
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	raw, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %v\n%s", err, stderr.String())
	}
	modCmd := exec.Command("go", "list", "-m")
	modCmd.Dir = dir
	mod, err := modCmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list -m: %v", err)
	}
	l := &loader{
		fset: token.NewFileSet(), module: strings.TrimSpace(string(mod)),
		pkgs: map[string]*pkgInfo{}, funcs: map[string]*funcInfo{}, exports: map[string]string{},
		litCount: map[string]int{},
	}
	var modPkgs []listedPkg
	dec := json.NewDecoder(bytes.NewReader(raw))
	for {
		var p listedPkg
		if err := dec.Decode(&p); err == io.EOF {
			break
		} else if err != nil {
			return nil, err
		}
		if p.Export != "" {
			l.exports[p.ImportPath] = p.Export
		}
		if strings.HasPrefix(p.ImportPath, l.module+"/") && !p.Standard {
			modPkgs = append(modPkgs, p)
		}
	}
	l.imp = importer.ForCompiler(l.fset, "gc", func(path string) (io.ReadCloser, error) {
		f, ok := l.exports[path]
		if !ok {
			return nil, fmt.Errorf("no export data for %s", path)
		}
		return os.Open(f)
	})
	for _, p := range modPkgs {
		if err := l.check(p); err != nil {
			return nil, err
		}
	}
	return l, nil
}

func (l *loader) check(p listedPkg) error {
	var files []*ast.File
	for _, name := range append(append([]string{}, p.GoFiles...), p.CgoFiles...) {
		f, err := parser.ParseFile(l.fset, filepath.Join(p.Dir, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return err
		}
		files = append(files, f)
	}
	info := &types.Info{
		Types: map[ast.Expr]types.TypeAndValue{}, Defs: map[*ast.Ident]types.Object{},
		Uses: map[*ast.Ident]types.Object{}, Selections: map[*ast.SelectorExpr]*types.Selection{},
	}
	var errs []string
	conf := types.Config{
		Importer: l.imp,
		Error:    func(err error) { errs = append(errs, err.Error()) },
	}
	pkg, _ := conf.Check(p.ImportPath, l.fset, files, info)
	if len(errs) > 0 {
		return fmt.Errorf("type-checking %s: %s", p.ImportPath, strings.Join(errs[:min(len(errs), 5)], "; "))
	}
	pi := &pkgInfo{path: p.ImportPath, files: files, pkg: pkg, info: info}
	l.pkgs[p.ImportPath] = pi
	for _, f := range files {
		for _, d := range f.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Body == nil {
				continue
			}
			if fn, ok := info.Defs[fd.Name].(*types.Func); ok {
				l.funcs[fn.FullName()] = &funcInfo{decl: fd, pkg: pi, name: l.display(fn)}
			}
		}
	}
	return nil
}

// display renders a function as pkg.Type.Method / pkg.Func without the module path.
func (l *loader) display(fn *types.Func) string {
	pkg := ""
	if fn.Pkg() != nil {
		pkg = fn.Pkg().Name()
	}
	sig := fn.Type().(*types.Signature)
	if r := sig.Recv(); r != nil {
		t := r.Type()
		if p, ok := t.(*types.Pointer); ok {
			t = p.Elem()
		}
		if n, ok := t.(*types.Named); ok {
			return pkg + "." + n.Obj().Name() + "." + fn.Name()
		}
	}
	return pkg + "." + fn.Name()
}

